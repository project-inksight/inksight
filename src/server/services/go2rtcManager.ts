import fs from 'fs';
import path from 'path';
import net from 'net';
import { spawn, execFileSync, ChildProcess } from 'child_process';
import { Camera } from '../../shared/types.js';
import { CameraRepository } from '../db/repositories.js';
import { binaryResolver } from './binaryResolver.js';
import { wsHub } from './wsHub.js';

const CONFIG_PATH = process.env.SENTINEL_DATA_DIR
  ? path.join(path.resolve(process.env.SENTINEL_DATA_DIR), 'go2rtc.yaml')
  : path.resolve(process.cwd(), 'go2rtc.yaml');
const GO2RTC_API_PORT = 1984;
const GO2RTC_RTSP_PORT = 8554;
const GO2RTC_WEBRTC_PORT = 8555;

export class Go2rtcManager {
  private proc: ChildProcess | null = null;
  private isOnline = false;
  private isStopping = false;
  private restartTimer: NodeJS.Timeout | null = null;
  private backoffMs = 2000;
  private reachabilityCache = new Map<string, boolean>();

  public getApiUrl(): string {
    return `http://127.0.0.1:${GO2RTC_API_PORT}`;
  }

  public getRtspBaseUrl(): string {
    return `rtsp://127.0.0.1:${GO2RTC_RTSP_PORT}`;
  }

  public getRtspPort(): number {
    return GO2RTC_RTSP_PORT;
  }

  public getConfigPath(): string {
    return CONFIG_PATH;
  }

  public getStatus(): { online: boolean; pid: number | null } {
    return {
      online: this.isOnline,
      pid: this.proc?.pid ?? null,
    };
  }

  public isCameraLanReachable(cameraId: string): boolean {
    return this.reachabilityCache.get(cameraId) ?? true;
  }

  public async checkRtspHostReachable(rtspUrl: string, timeoutMs = 1500): Promise<boolean> {
    try {
      const parsed = new URL(rtspUrl);
      const host = parsed.hostname;
      const port = Number(parsed.port || 554);
      if (!host) return false;

      return await new Promise<boolean>((resolve) => {
        const socket = new net.Socket();
        let settled = false;
        const done = (result: boolean) => {
          if (!settled) {
            settled = true;
            socket.destroy();
            resolve(result);
          }
        };

        socket.setTimeout(timeoutMs);
        socket.once('connect', () => done(true));
        socket.once('timeout', () => done(false));
        socket.once('error', () => done(false));
        socket.connect(port, host);
      });
    } catch {
      return false;
    }
  }

  public async refreshReachabilityForAllCameras(): Promise<void> {
    const cameras = CameraRepository.getAll();
    for (const cam of cameras) {
      const isReachable = await this.checkRtspHostReachable(cam.main_stream_url);
      this.reachabilityCache.set(cam.id, isReachable);
    }
  }

  /**
   * Generates go2rtc.yaml from all enabled cameras in SQLite.
   * Implements:
   * - Dual stream ingestion: {camera_id}_main and {camera_id}_sub
   * - Audio compatibility transcoding (#audio=aac / #audio=opus) for G.711/PCMU/PCMA cameras
   * - Optional Force GPU H.264 Transcode (NVENC) via #video=h264#hardware when force_h264 is enabled
   */
  public generateConfigYaml(cameras?: Camera[]): string {
    const allCameras = cameras ?? CameraRepository.getAll();
    const ffmpegBin = binaryResolver.resolveFFmpeg().replace(/\\/g, '/');

    const lines: string[] = [
      '# Auto-generated by SentinelVMS Pro - Do not edit manually while server is running',
      'api:',
      `  listen: ":${GO2RTC_API_PORT}"`,
      '  origin: "*"',
      '',
      'rtsp:',
      `  listen: ":${GO2RTC_RTSP_PORT}"`,
      '  default_query: "video&audio"',
      '',
      'webrtc:',
      `  listen: ":${GO2RTC_WEBRTC_PORT}"`,
      '  candidates:',
      '    - 127.0.0.1:8555',
      '    - stun:8555',
      '',
      'ffmpeg:',
      `  bin: "${ffmpegBin}"`,
      '  global: "-hide_banner"',
      '  h264: "-c:v libx264 -preset superfast -tune zerolatency -pix_fmt yuv420p"',
      '',
      'log:',
      '  level: info',
      '',
      'streams:',
    ];

    const enabledCameras = allCameras.filter((c) => c.enabled);

    if (enabledCameras.length === 0) {
      lines.push('  {}');
    } else {
      for (const cam of enabledCameras) {
        const audioTag =
          cam.audio_compat === 'copy'
            ? ''
            : cam.audio_compat === 'opus'
              ? '#audio=opus#audio=aac'
              : '#audio=aac#audio=opus';

        // Main High-Res (4K) Stream
        lines.push(`  # Camera: ${cam.name} (${cam.ip_address})`);
        lines.push(`  ${cam.id}_main:`);
        if (cam.force_h264) {
          lines.push(`    - "ffmpeg:${cam.main_stream_url}#video=h264#hardware${audioTag}"`);
        } else {
          lines.push(`    - "${cam.main_stream_url}"`);
          if (audioTag) {
            lines.push(`    - "ffmpeg:${cam.id}_main${audioTag}"`);
          }
        }

        // Sub Low-Res (720p/D1) Stream for Grid Matrix & AI Sampler
        const subUrl = cam.sub_stream_url || cam.main_stream_url;
        lines.push(`  ${cam.id}_sub:`);
        if (cam.force_h264) {
          lines.push(`    - "ffmpeg:${subUrl}#video=h264#hardware${audioTag}"`);
        } else {
          lines.push(`    - "${subUrl}"`);
          if (audioTag) {
            lines.push(`    - "ffmpeg:${cam.id}_sub${audioTag}"`);
          }
        }
      }
    }

    const yamlContent = lines.join('\n') + '\n';
    const configDir = path.dirname(CONFIG_PATH);
    if (!fs.existsSync(configDir)) {
      fs.mkdirSync(configDir, { recursive: true });
    }
    fs.writeFileSync(CONFIG_PATH, yamlContent, 'utf8');
    return yamlContent;
  }

  private killAnyExistingProcess(): void {
    if (this.proc) {
      try {
        this.proc.kill();
      } catch {
        // ignore
      }
      this.proc = null;
    }
    if (process.platform === 'win32') {
      try {
        execFileSync('taskkill', ['/F', '/IM', 'go2rtc.exe'], { stdio: 'ignore' });
      } catch {
        // ignore when no go2rtc.exe is running
      }
    }
  }

  public async start(): Promise<void> {
    this.isStopping = false;
    await this.refreshReachabilityForAllCameras();
    this.generateConfigYaml();

    // Check if an instance is already responding on 1984
    if (await this.checkApiHealth()) {
      console.log('[go2rtc] Detected running go2rtc instance on port 1984');
      this.isOnline = true;
      return;
    }

    const binPath = await binaryResolver.ensureGo2rtcBinary();
    if (!fs.existsSync(binPath)) {
      console.warn(
        `[go2rtc] Binary not found at ${binPath}. Operating in direct FFmpeg fallback mode until go2rtc is available.`
      );
      this.isOnline = false;
      return;
    }

    this.killAnyExistingProcess();

    console.log(`[go2rtc] Launching ${binPath} -config ${CONFIG_PATH}`);
    this.proc = spawn(binPath, ['-config', CONFIG_PATH], {
      cwd: process.cwd(),
      stdio: ['ignore', 'pipe', 'pipe'],
      windowsHide: true,
    });

    this.proc.stdout?.on('data', (chunk: Buffer) => {
      const text = chunk.toString().trim();
      if (text && (text.includes('ERR') || text.includes('api') || text.includes('rtsp'))) {
        console.log(`[go2rtc] ${text}`);
      }
    });

    this.proc.stderr?.on('data', (chunk: Buffer) => {
      const text = chunk.toString().trim();
      if (text) {
        console.warn(`[go2rtc:err] ${text}`);
      }
    });

    this.proc.on('exit', (code, signal) => {
      this.isOnline = false;
      this.proc = null;
      if (!this.isStopping) {
        console.warn(
          `[go2rtc] Process exited (code=${code}, signal=${signal}). Scheduling restart in ${this.backoffMs}ms`
        );
        if (this.restartTimer) clearTimeout(this.restartTimer);
        this.restartTimer = setTimeout(() => {
          this.backoffMs = Math.min(this.backoffMs * 2, 30000);
          void this.start();
        }, this.backoffMs);
      }
    });

    // Wait up to 4 seconds for API readiness
    for (let i = 0; i < 8; i++) {
      await new Promise((r) => setTimeout(r, 400));
      if (await this.checkApiHealth()) {
        this.isOnline = true;
        this.backoffMs = 2000;
        console.log(
          '[go2rtc] Engine online on Port 1984 (API/MSE/WebRTC) & Port 8554 (RTSP Restream)'
        );
        break;
      }
    }
  }

  public async checkApiHealth(): Promise<boolean> {
    try {
      const res = await fetch(`${this.getApiUrl()}/api`, {
        signal: AbortSignal.timeout(2000),
      });
      this.isOnline = res.ok;
      return res.ok;
    } catch {
      this.isOnline = false;
      return false;
    }
  }

  public async getActiveStreamsInfo(): Promise<Record<string, unknown>> {
    try {
      const res = await fetch(`${this.getApiUrl()}/api/streams`, {
        signal: AbortSignal.timeout(2000),
      });
      if (!res.ok) return {};
      return (await res.json()) as Record<string, unknown>;
    } catch {
      return {};
    }
  }

  public async reload(): Promise<void> {
    this.isStopping = true;
    this.killAnyExistingProcess();
    await new Promise((r) => setTimeout(r, 250));
    await this.start();
    wsHub.notify('info', 'go2rtc Engine Reloaded', 'Stream ingestion configuration updated.');
  }

  public stop(): void {
    this.isStopping = true;
    if (this.restartTimer) {
      clearTimeout(this.restartTimer);
      this.restartTimer = null;
    }
    this.killAnyExistingProcess();
    this.isOnline = false;
  }
}

export const go2rtcManager = new Go2rtcManager();
